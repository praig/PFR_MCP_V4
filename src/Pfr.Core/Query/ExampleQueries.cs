namespace Pfr.Core.Query;

/// <summary>A ready-made query to start from.</summary>
public sealed record ExampleQuery(string Title, string Sql);

/// <summary>
/// Example queries shown in the Explore data page. Every one is run against a test snapshot in the tests,
/// so they stay in step with the table and column names.
/// </summary>
public static class ExampleQueries
{
    public static readonly IReadOnlyList<ExampleQuery> All =
    [
        new("Members, roles and services",
            "SELECT host_name, role, ha_enabled, services\nFROM members\nORDER BY host_name"),

        new("Every service on every member",
            "SELECT m.host_name, s.service\nFROM members m\nJOIN member_services s ON s.member_oid = m.oid\nORDER BY m.host_name, s.service"),

        new("Licenses, soonest expiry first",
            "SELECT l.name, m.host_name, l.kind, l.expires\nFROM licenses l\nLEFT JOIN members m ON m.oid = l.member_oid\nWHERE l.expires IS NOT NULL\nORDER BY l.expires\nLIMIT 50"),

        new("Record counts by type",
            "SELECT type, COUNT(*) AS records\nFROM records\nGROUP BY type\nORDER BY records DESC"),

        new("Largest zones by record count",
            "SELECT z.fqdn, z.zone_type, COUNT(*) AS records\nFROM zones z\nJOIN records r ON r.zone_key = z.zone_key\nGROUP BY z.zone_key\nORDER BY records DESC\nLIMIT 25"),

        new("Networks with no DHCP range",
            "SELECT n.prefix, n.comment\nFROM networks n\nLEFT JOIN dhcp_ranges r ON r.network_key = n.network_key\nWHERE n.is_container = 0 AND r.network_key IS NULL\nORDER BY ip_key(n.prefix)"),

        new("DHCP ranges by serving member",
            "SELECT m.host_name, r.start_address, r.end_address, r.association_type, r.failover_name\nFROM dhcp_ranges r\nLEFT JOIN members m ON m.oid = r.member_oid\nORDER BY m.host_name, ip_key(r.start_address)"),

        new("A records inside a network",
            "SELECT fqdn, value AS address\nFROM records\nWHERE type = 'A' AND cidr_contains('10.0.0.0/8', value)\nORDER BY ip_key(value)"),

        new("Addresses used inside each DHCP range",
            "SELECT r.start_address, r.end_address, rec.fqdn, rec.value AS address\nFROM dhcp_ranges r\nJOIN records rec ON rec.type = 'A' AND ip_in_range(rec.value, r.start_address, r.end_address)\nORDER BY ip_key(rec.value)\nLIMIT 1000"),

        new("Authoritative zones with no secondary server",
            "SELECT z.fqdn\nFROM zones z\nWHERE z.zone_type = 'Authoritative'\n  AND NOT EXISTS (SELECT 1 FROM zone_servers s\n                  WHERE s.zone_key = z.zone_key AND s.role IN ('grid_secondary', 'external_secondary'))\nORDER BY z.fqdn"),

        new("Records generated by host objects",
            "SELECT host_name, type, fqdn, value\nFROM records\nWHERE is_from_host = 1\nORDER BY host_name, type"),

        new("IPAM-only hosts (no DNS records)",
            "SELECT host_name, address, network_view_id, configure_for_dhcp, mac_address\nFROM hosts\nWHERE is_dns_host = 0\nORDER BY ip_key(address)"),

        new("Hosts with more than one address",
            "SELECT host_name, COUNT(*) AS addresses, group_concat(address, ', ') AS address_list\nFROM hosts\nGROUP BY zone_key, host_name\nHAVING COUNT(*) > 1\nORDER BY host_name"),

        new("Host addresses in no network",
            "SELECT h.host_name, h.address, h.network_view_id\nFROM hosts h\nWHERE NOT EXISTS (SELECT 1 FROM networks n\n                  WHERE n.is_container = 0 AND n.network_view_id = h.network_view_id\n                    AND cidr_contains(n.prefix, h.address) = 1)\nORDER BY ip_key(h.address)"),

        new("Everything that is disabled",
            "SELECT 'zone' AS kind, fqdn AS name FROM zones WHERE disabled = 1\nUNION ALL\nSELECT 'network', prefix FROM networks WHERE disabled = 1\nUNION ALL\nSELECT 'DHCP range', start_address || ' - ' || end_address FROM dhcp_ranges WHERE disabled = 1\nUNION ALL\nSELECT 'record', fqdn FROM records WHERE disabled = 1"),

        new("Admin users, their groups and last sign-in",
            "SELECT u.name, u.group_name, u.is_superuser, u.auth_type, u.disabled, u.last_login\nFROM admin_users u\nWHERE u.is_internal = 0\nORDER BY u.is_superuser DESC, u.name"),

        new("Admin groups with their roles and number of users",
            "SELECT g.name, g.is_superuser, g.user_count, COALESCE(group_concat(r.role_name, ', '), '') AS roles\nFROM admin_groups g\nLEFT JOIN admin_group_roles r ON r.group_name = g.name\nGROUP BY g.name\nORDER BY g.name"),

        new("Permissions each admin group has, directly and through roles",
            "SELECT g.name AS admin_group, 'group' AS via, p.resource_type, p.resource_key, p.sub_type, p.permission\nFROM admin_groups g\nJOIN admin_permissions p ON p.owner_type = 'group' AND p.owner_name = g.name\nWHERE p.unmanaged = 0\nUNION ALL\nSELECT g.name, 'role: ' || gr.role_name, p.resource_type, p.resource_key, p.sub_type, p.permission\nFROM admin_groups g\nJOIN admin_group_roles gr ON gr.group_name = g.name\nJOIN admin_permissions p ON p.owner_type = 'role' AND p.owner_name = gr.role_name\nORDER BY 1, 3, 4"),

        new("Admin users who can use the API",
            "SELECT u.name, u.group_name, a.interface\nFROM admin_users u\nJOIN admin_access a ON a.owner_type = 'group' AND a.owner_name = u.group_name\nWHERE a.allowed = 1 AND a.interface IN ('papi', 'cloud_api')\nORDER BY u.name, a.interface"),
    ];
}
